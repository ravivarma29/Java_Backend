package com.loops;

public class ForTask {
	public static void main(String[] args) {
		
		// when we know the number of Iterations
		for(int i=1;i<=2;i++ )
		{
			System.out.println( "Increment of i is " + i);
		}
		System.out.println("-----");
		for(int i=2;i>=0;i-- )
		{
			System.out.println( "Decrement of i is " + i);
		}
		for(int i=9;i>=3;i-- )
		{
			System.out.println( "Decrement of i is " + i);
		}
	}

}
