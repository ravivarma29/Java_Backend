package com.casting;

public class ImplicitCasting {
	public static void main(String[] args) {
		byte num1=123;
		short num2=num1;
		int num3=num2;
		long num4=num3;
		float num5 =12.04f;
		double num6=1235.45628;
		System.out.println(num6);
		//ASCII
		int num8 = 'c';
		System.out.println(num8);
		
		
		
	}

}
