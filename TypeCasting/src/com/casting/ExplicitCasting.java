package com.casting;

public class ExplicitCasting {
	public static void main(String[] args) {
		short s=127;
		byte b=(byte) s;
		System.out.println(b);
		
		double l=12345.8742;
		float f=(long) l;
		System.out.println(f);
		
		float f1=123.76356f;
		int num=(int)f1;
		System.out.println(num);
				
	}

}
